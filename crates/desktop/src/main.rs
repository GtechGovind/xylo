use gpui_kit::component::{Theme, ThemeMode};
use gpui_kit::{prelude::*, *};
use xylo_runtime::host::HostClient;
// Development executables must not inherit the installed release shortcut's
// icon and relaunch target. Release builds retain the stable application ID.
#[cfg(all(target_os = "windows", debug_assertions))]
const SHELL_APPLICATION_ID: &str = "com.qurkos.xylo.dev";
#[cfg(not(all(target_os = "windows", debug_assertions)))]
const SHELL_APPLICATION_ID: &str = xylo_core::APPLICATION_ID;
actions!(xylo, [ShowXylo]);
struct ShellState {
    window: AnyWindowHandle,
    view: Entity<xylo::Xylo>,
    _tray: Option<tray_icon::TrayIcon>,
}
impl Global for ShellState {}
fn show(cx: &mut App) {
    if let Some(state) = cx.try_global::<ShellState>() {
        let window = state.window;
        cx.activate(true);
        let _ = cx.update_window(window, |_, window, _| window.activate_window());
    }
}
fn quit(cx: &mut App) {
    if let Some(state) = cx.try_global::<ShellState>() {
        let view = state.view.clone();
        let window = state.window;
        let _ = cx.update_window(window, |_, window, cx| {
            view.update(cx, |view, cx| view.request_quit(window, cx))
        });
    } else {
        cx.quit();
    }
}
fn configure_shell_actions(cx: &mut App) {
    cx.on_action(|_: &ShowXylo, cx| show(cx));
    // Global key dispatch borrows the window; wait for GPUI to restore it.
    cx.on_action(|_: &xylo::QuitApplication, cx| cx.defer(quit));
    // Sharing the root's action preserves the native menu accelerator. A
    // different action bound to that chord would shadow the focused route.
    cx.set_menus([Menu::new("Xylo").items([
        MenuItem::action("Open Xylo", ShowXylo),
        MenuItem::Separator,
        MenuItem::action("Quit Xylo", xylo::QuitApplication),
    ])]);
}
fn configure_window_close(has_tray: bool, window: &mut Window, cx: &App) {
    window.on_window_should_close(cx, move |window, cx| {
        if has_tray && cfg!(target_os = "macos") {
            cx.hide();
        } else {
            let view = cx
                .try_global::<ShellState>()
                .map(|state| state.view.clone());
            if let Some(view) = view {
                view.update(cx, |view, cx| view.request_quit(window, cx));
            } else {
                cx.quit();
            }
        }
        false
    });
}
fn main() -> anyhow::Result<()> {
    let (data, debug) = match startup::Command::parse(std::env::args_os().skip(1))? {
        startup::Command::Version => {
            println!(
                "{} {}",
                xylo_core::APPLICATION_NAME,
                env!("CARGO_PKG_VERSION")
            );
            return Ok(());
        }
        startup::Command::Help => {
            println!(
                "Xylo {}\n\nUsage: xylo [--data-dir ABSOLUTE_PATH] [--debug] | --version | --help\n\nWithout options, Xylo opens the existing application profile.",
                env!("CARGO_PKG_VERSION")
            );
            return Ok(());
        }
        startup::Command::Launch { data, debug } => (data, debug),
    };
    let paths = match data {
        Some(data) => xylo_runtime::AppPaths::at(data)?,
        None => xylo_runtime::AppPaths::discover()?,
    };
    let _observability = xylo_runtime::observability::Observability::init(&paths.data, debug)?;
    let host = HostClient::spawn_at(paths);
    let application = gpui_kit::application()
        .with_assets(assets::AppAssets)
        .with_quit_mode(QuitMode::Explicit);
    application.on_reopen(show);
    application.run(move |cx| {
        cx.set_app_identity(SHELL_APPLICATION_ID, xylo_core::APPLICATION_NAME);
        #[cfg(target_os = "macos")]
        if let Err(error) = app_icon::install() {
            tracing::warn!(%error, "The macOS Dock icon could not be installed");
        }
        gpui_kit::init(cx);
        Theme::change(ThemeMode::Light, None, cx);
        cx.set_window_appearance(Some(WindowAppearance::Light));
        let tray = tray::create();
        if let Err(error) = &tray {
            tracing::warn!(%error,"Tray unavailable; closing the window quits Xylo");
        }
        let (tray, events) = match tray {
            Ok((tray, events)) => (Some(tray), Some(events)),
            Err(_) => (None, None),
        };
        let has_tray = tray.is_some();
        let opened = gpui_kit::open_window(
            WindowOptions {
                // Match the launcher basename generated by the pinned packager
                // for Wayland desktop lookup and X11 taskbar grouping.
                #[cfg(target_os = "linux")]
                app_id: Some("xylo".into()),
                window_bounds: Some(WindowBounds::Windowed(Bounds::centered(
                    None,
                    size(px(1380.), px(880.)),
                    cx,
                ))),
                window_min_size: Some(size(px(1000.), px(680.))),
                // X11 supports a per-window icon supplied directly as pixels.
                #[cfg(target_os = "linux")]
                icon: Some(std::sync::Arc::new(ui::brand_pixels(64))),
                titlebar: Some(TitlebarOptions {
                    title: Some("Xylo".into()),
                    ..Default::default()
                }),
                ..Default::default()
            },
            cx,
            move |window, cx| {
                configure_window_close(has_tray, window, cx);
                cx.new(|cx| xylo::Xylo::new(host, window, cx))
            },
        );
        let (window, view) = match opened {
            Ok(opened) => opened,
            Err(error) => {
                tracing::error!(%error, "The main window could not be opened");
                cx.quit();
                return;
            }
        };
        cx.set_global(ShellState {
            window,
            view,
            _tray: tray,
        });
        configure_shell_actions(cx);
        if let Some(events) = events {
            cx.spawn(async move |cx| {
                while let Ok(event) = events.recv().await {
                    cx.update(|cx| match event {
                        tray::Event::Show => show(cx),
                        tray::Event::Quit => quit(cx),
                    });
                }
            })
            .detach();
        }
        cx.activate(true);
    });
    Ok(())
}
